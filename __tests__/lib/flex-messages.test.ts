const footerAction = (
  card: CardElement
): { displayText: string; label: string } | undefined => {
  const contents = buildFlexMessage(card).contents as unknown as {
    footer: {
      contents: { action: { displayText: string; label: string } }[];
    };
  };
  return contents.footer.contents[0]?.action;
};

const bubbleOf = (card: CardElement): messagingApi.FlexBubble => {
  const { contents } = buildFlexMessage(card);
  if (contents.type !== "bubble") {
    throw new Error("expected a bubble");
  }
  return contents;
};

const textsIn = (
  component: messagingApi.FlexComponent | undefined
): string[] => {
  if (component?.type === "text") {
    return [component.text ?? ""];
  }
  if (component?.type === "box") {
    return component.contents.flatMap(textsIn);
  }
  return [];
};

const bodyTexts = (card: CardElement): string[] => textsIn(bubbleOf(card).body);

const footerActions = (card: CardElement): messagingApi.Action[] =>
  (bubbleOf(card).footer?.contents ?? []).flatMap((component) =>
    component.type === "button" ? [component.action] : []
  );

const gridRows = (grid: messagingApi.FlexComponent | undefined): string[][] => {
  if (grid?.type !== "box") {
    throw new Error("expected a grid box");
  }
  return grid.contents.map((row) =>
    row.type === "box"
      ? row.contents.map((cell) =>
          cell.type === "text" ? (cell.text ?? "") : ""
        )
      : []
  );
};

